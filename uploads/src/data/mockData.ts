// Helper function to generate new audit entries
export const createAuditEntry = (
  action: AuditLogEntry['action'],
  actor: string,
  actorType: AuditLogEntry['actorType'],
  target: string,
  targetType: AuditLogEntry['targetType'],
  details: string,
  previousHash: string
): AuditLogEntry => ({
  id: `audit-${Date.now()}`,
  timestamp: new Date().toISOString(),
  action,
  actor,
  actorType,
  target,
  targetType,
  details,
  hash: generateHash(),
  previousHash,
});
